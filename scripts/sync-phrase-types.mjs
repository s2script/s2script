#!/usr/bin/env node
/**
 * Write each plugin's phrase-key declaration from its phrase file.
 *
 * `translations/<name>.phrases.json` is the single source of truth — hand-authored, shipped in the
 * addon, edited by operators. This derives TYPES from those files, never data: the generated
 * declaration lists key NAMES so `cmd.replyT` and `Translations.translate` check them, and contains
 * no phrase text. It is gitignored and regenerated, in the spirit of `.svelte-kit/types`.
 *
 * WHICH files a plugin gets is read from its own `ctx.translations.load("a", "b")` or
 * `translations.load("a", "b")` call (load-window free API). Nothing is
 * loaded automatically, so a key from a file the plugin did not load is a compile error rather than
 * raw key text printed to a player — SourceMod's rule, caught at build instead of at runtime.
 *
 * A plugin that loads nothing gets no declaration, and its keys fall back to plain `string` (see
 * `PhraseKey` in packages/sdk/phrases.d.ts) — so a brand-new plugin compiles before this has run.
 *
 * Run:  node --experimental-strip-types scripts/sync-phrase-types.mjs
 *       node --experimental-strip-types scripts/sync-phrase-types.mjs --check   # exit 1 if stale
 */
import { readdirSync, existsSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import ts from "typescript";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TRANSLATIONS = join(ROOT, "translations");
const COMMON = join(TRANSLATIONS, "common.phrases.json");
const GENERATED = "phrases.generated.d.ts";
const check = process.argv.includes("--check");

/** Every plugin directory, under both the shipped and the opt-in tree. */
function pluginDirs() {
  const out = [];
  for (const base of ["plugins", join("plugins", "disabled")]) {
    const abs = join(ROOT, base);
    if (!existsSync(abs)) continue;
    for (const e of readdirSync(abs, { withFileTypes: true })) {
      // `disabled` is a directory OF plugins, not a plugin.
      if (!e.isDirectory() || e.name === "disabled") continue;
      const src = join(abs, e.name, "src");
      if (existsSync(src)) out.push({ name: e.name, src });
    }
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/** Keys of a phrase file, or null when it does not exist. Throws on malformed JSON — a phrase file
 *  that does not parse is a real error, not something to skip past silently. */
function keysOf(file) {
  if (!existsSync(file)) return null;
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new Error(`${relative(ROOT, file)}: not valid JSON — ${err.message}`);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error(`${relative(ROOT, file)}: expected an object of key -> phrase`);
  }
  for (const [k, v] of Object.entries(parsed)) {
    if (typeof v !== "string") {
      throw new Error(`${relative(ROOT, file)}: phrase "${k}" must be a string, got ${typeof v}`);
    }
  }
  return Object.keys(parsed);
}

function render(name, sets, keys) {
  // Sorted and de-duplicated so the file is stable regardless of key order in the sources, and a key
  // present in more than one loaded file does not appear twice.
  const all = [...new Set(keys)].sort();
  const entries = all.map((k) => `    ${JSON.stringify(k)}: true;`).join("\n");
  return `// GENERATED by scripts/sync-phrase-types.mjs — do not edit, and do not commit.
// Source: ${sets.map((n) => `translations/${n}.phrases.json`).join(' + ')}
//
// Key NAMES only, from the files this plugin loads: this is what makes \`cmd.replyT\` and
// \`Translations.translate\` check their key. The phrases live in the JSON, never duplicated here.
export {};
declare module "@s2script/sdk/phrases" {
  interface PhraseKeys {
${entries}
  }
}
`;
}

/**
 * The phrase-file names a plugin declares, from `ctx.translations.load("a", "b")` or
 * identifier `translations.load("a", "b")` (the ctx-free load-window form).
 *
 * Parsed with the TypeScript compiler API, not a regex: a regex matches the same text inside a
 * comment or a string, and a conversion like this leaves commented-out calls behind. Only literal
 * arguments are collected — a name built at runtime is skipped rather than guessed at, and simply
 * goes unchecked.
 */
function declaredSets(srcDir) {
  const names = [];
  const walkDir = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, e.name);
      if (e.isDirectory()) { walkDir(full); continue; }
      if (!/\.(ts|mts|js|mjs)$/.test(e.name)) continue;
      if (e.name.endsWith(".d.ts")) continue;
      const sf = ts.createSourceFile(full, readFileSync(full, "utf8"), ts.ScriptTarget.Latest, false);
      const visit = (node) => {
        if (
          ts.isCallExpression(node) &&
          ts.isPropertyAccessExpression(node.expression) &&
          node.expression.name.text === "load"
        ) {
          const recv = node.expression.expression;
          const fromCtx = ts.isPropertyAccessExpression(recv) && recv.name.text === "translations";
          const fromIdent = ts.isIdentifier(recv) && recv.text === "translations";
          if (fromCtx || fromIdent) {
            for (const a of node.arguments) if (ts.isStringLiteralLike(a)) names.push(a.text);
          }
        }
        ts.forEachChild(node, visit);
      };
      ts.forEachChild(sf, visit);
    }
  };
  walkDir(srcDir);
  return names;
}

let stale = 0;
for (const p of pluginDirs()) {
  const dest = join(p.src, GENERATED);
  const sets = declaredSets(p.src);
  const current = existsSync(dest) ? readFileSync(dest, "utf8") : null;

  // A name the plugin loads that has no phrase file is a real error: every key from it would fall
  // through to raw text at runtime, and the types would say nothing is wrong.
  const missing = sets.filter((n) => keysOf(join(TRANSLATIONS, `${n}.phrases.json`)) === null);
  if (missing.length) {
    console.error(`ERROR: ${p.name} loads ${missing.map((m) => JSON.stringify(m)).join(", ")}, `
      + `which ${missing.length === 1 ? "has" : "have"} no translations/<name>.phrases.json`);
    process.exit(1);
  }

  const keys = sets.flatMap((n) => keysOf(join(TRANSLATIONS, `${n}.phrases.json`)));
  // Loads nothing -> no declaration. Any leftover one is removed: it would otherwise keep checking
  // keys against files this plugin no longer uses. Only ever this generated name, nothing else.
  if (sets.length === 0) {
    if (current === null) continue;
    if (check) { console.error(`STALE: ${relative(ROOT, dest)} — the plugin loads no phrases`); stale++; }
    else { rmSync(dest); console.log(`removed ${relative(ROOT, dest)}`); }
    continue;
  }

  const text = render(p.name, sets, keys);
  if (current === text) continue;
  if (check) { console.error(`STALE: ${relative(ROOT, dest)}`); stale++; }
  else { writeFileSync(dest, text); console.log(`wrote ${relative(ROOT, dest)}`); }
}

if (check && stale > 0) {
  console.error(`\n${stale} phrase declaration(s) out of date — run: node --experimental-strip-types scripts/sync-phrase-types.mjs`);
  process.exit(1);
}
console.log(check ? "PASS: phrase declarations are up to date" : "phrase declarations synced");
